# Descripción: Escribir un programa que convierta un valor dado en grados Fahrenheit a grados Celsius. 
# Recordar que la fórmula para la conversión es: C = (F-32)*5/9

grados=float(input("Dime una cantidad de grados Fahrenheit: "))

print("En celsius sería: ", (grados-32)*5/9)